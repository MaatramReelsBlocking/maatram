/* App Gate "In the Mood": 2/3/4 hr chips, reward table and payout. jsdom, no network. */
const fs = require('fs'), { JSDOM } = require('jsdom');
let pass = 0, fail = 0;
const ok = (n, c) => { c ? pass++ : fail++; console.log((c ? 'PASS ' : 'FAIL ') + n); };
const html = fs.readFileSync(__dirname + '/app-gate.html', 'utf8');
const d = new JSDOM(html).window.document;
const chips = [...d.querySelectorAll('#chips .chip')].map(c => +c.dataset.min);
ok('chips: 5..60 then In the Mood 90/120/180, no 4 hr', chips.join() === '5,10,15,25,45,60,90,120,180' && !chips.includes(240));
ok('In the Mood title groups 90 min, 2 hr, 3 hr', /<span class="chips-t">In the Mood<\/span>\s*<button class="chip" data-min="90">90 min<\/button>\s*<button class="chip" data-min="120">2 hr<\/button>\s*<button class="chip" data-min="180">3 hr<\/button>/.test(html));
ok('reward rows 90 min +180, 2 hr +300, 3 hr +500 under the title', /<tr class="mood"><td colspan="2">In the Mood<\/td><\/tr>\s*<tr><td>90 min<\/td><td>\+180 pts<\/td><\/tr>\s*<tr><td>2 hr<\/td><td>\+300 pts<\/td><\/tr>\s*<tr><td>3 hr<\/td><td>\+500 pts<\/td><\/tr>/.test(html) && !/4 hr/.test(html));
const src = html.match(/const MOOD=[\s\S]*?return t\?t\[1\]:0; \};/)[0];
const moodPts = new Function(src + '; return moodPts;')();
const earned = t => Math.max(Math.floor(t / 300) * 10, moodPts(t));
const m = x => x * 60;
ok('90 min unchanged: +180', earned(m(90)) === 180);
ok('119 min stays on the old rate (+230)', earned(m(119)) === 230);
ok('2 hr = +300', earned(m(120)) === 300);
ok('150 min never pays less than the rate (+300)', earned(m(150)) === 300);
ok('3 hr = +500', earned(m(180)) === 500);
ok('a lock above 3 hr is not offered: no 4 hr tier', moodPts(m(240)) === 500);
ok('claimLock uses the new formula', /Math\.max\(Math\.floor\(total\/300\)\*10, moodPts\(total\)\)/.test(html));
ok('api accepts up to 180 min', /const MAX_MIN = 180;/.test(fs.readFileSync(__dirname + '/api/link.js', 'utf8')));
ok('extension and apps untouched (extension cap still 180)', /minutes > 180/.test(fs.readFileSync(__dirname + '/chrome-extension/background.js', 'utf8')));
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
